/**
 * Audit / step timestamps are anchored to a fixed "morning of the demo" time so
 * the reasoning timeline reads like a real incident log (10:04, 10:05, ...).
 */
const DEMO_DAY = new Date();
DEMO_DAY.setHours(10, 0, 0, 0);

/** Minutes (and optional seconds) after the demo anchor, as an ISO string. */
export function at(minutes: number, seconds = 0): string {
  return new Date(DEMO_DAY.getTime() + (minutes * 60 + seconds) * 1000).toISOString();
}

/** Minutes before "now" — used for agent last-activity relative times. */
function ago(minutes: number): string {
  return new Date(Date.now() - minutes * 60_000).toISOString();
}

